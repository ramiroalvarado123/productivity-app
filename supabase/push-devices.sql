-- AVORA: notificaciones push de la app nativa (iPhone y Android).
-- Ejecutar una sola vez desde Supabase > SQL Editor, después de notifications.sql. Es aditivo.
--
-- Guarda el token de cada celular donde alguien activó los avisos. Las suscripciones del
-- navegador (Web Push) siguen en `push_subscriptions`.

create table if not exists public.push_devices (
  id bigint generated by default as identity primary key,
  user_email text not null references public.profiles(email) on delete cascade,
  platform text not null check (platform in ('ios', 'android')),
  token text not null unique,
  app_version text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists push_devices_user_email_idx on public.push_devices (user_email);

alter table public.push_devices enable row level security;

drop policy if exists owner_access on public.push_devices;
create policy owner_access on public.push_devices for all to authenticated
  using (user_email = (select auth.jwt() ->> 'email'))
  with check (user_email = (select auth.jwt() ->> 'email'));

grant select, insert, update, delete on public.push_devices to authenticated;

-- Registrar el celular de quien tiene la sesión. Va por una función `security definer` porque
-- el token puede haber quedado a nombre de otra cuenta que usó antes ese mismo celular, y una
-- política de RLS no deja pisar filas ajenas. También deja activado el permiso de avisos.
create or replace function public.avora_register_push_device(p_token text, p_platform text, p_app_version text default '')
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := auth.jwt() ->> 'email';
begin
  if auth.uid() is null or coalesce(v_email, '') = '' then
    raise exception 'Necesitás iniciar sesión.';
  end if;
  if p_platform not in ('ios', 'android') or coalesce(p_token, '') = '' then
    raise exception 'Dispositivo inválido.';
  end if;

  insert into public.profiles (email, display_name)
    values (v_email, split_part(v_email, '@', 1))
    on conflict (email) do nothing;

  insert into public.push_devices (user_email, platform, token, app_version)
    values (v_email, p_platform, p_token, left(coalesce(p_app_version, ''), 40))
    on conflict (token) do update
      set user_email = excluded.user_email, platform = excluded.platform,
          app_version = excluded.app_version, updated_at = now();

  insert into public.notification_preferences (user_email, push_enabled)
    values (v_email, true)
    on conflict (user_email) do update set push_enabled = true;
end;
$$;

revoke all on function public.avora_register_push_device(text, text, text) from public, anon;
grant execute on function public.avora_register_push_device(text, text, text) to authenticated;
