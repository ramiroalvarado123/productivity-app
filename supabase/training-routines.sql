-- Rutinas de entrenamiento: listas de ejercicios con nombre (Pull, Push, Piernas…)
-- que se cargan de una vez en la planilla del día.
-- Ejecutar una vez en Supabase > SQL Editor. Es aditivo. Mientras no exista, la app
-- sigue funcionando: no hay rutinas guardadas y al crear una avisa que falta este SQL.
create table if not exists public.training_routines (
  id bigint generated by default as identity primary key,
  user_email text not null,
  name text not null check (char_length(name) between 1 and 40),
  -- [{ "exercise": "Dominadas", "sets": 4 }, …]
  exercises_json text not null default '[]',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_email, name)
);
create index if not exists training_routines_user_email_idx on public.training_routines (user_email, created_at);

alter table public.training_routines enable row level security;
drop policy if exists owner_access on public.training_routines;
create policy owner_access on public.training_routines for all to authenticated
  using (user_email = (select auth.jwt() ->> 'email'))
  with check (user_email = (select auth.jwt() ->> 'email'));

grant select, insert, update, delete on public.training_routines to authenticated;
grant usage, select on sequence public.training_routines_id_seq to authenticated;
