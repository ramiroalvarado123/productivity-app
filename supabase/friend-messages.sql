-- AVORA: chat entre amigos (reemplaza al "Mandar un mensaje" por mail).
-- Ejecutar completo una sola vez desde Supabase > SQL Editor, después de friends.sql. Es aditivo.
--
-- Cada mensaje es una fila. Solo lo ven quien lo escribió y quien lo recibe, y solo se
-- puede escribir a alguien que ya está en tu círculo. Marcar como leído va por función
-- (no hay política de update): así nadie puede editar el texto de un mensaje ajeno.

create table if not exists public.friend_messages (
  id bigint generated by default as identity primary key,
  from_email text not null,
  to_email text not null,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists friend_messages_pair_idx on public.friend_messages (from_email, to_email, id desc);
create index if not exists friend_messages_inbox_idx on public.friend_messages (to_email, read_at, id desc);

alter table public.friend_messages enable row level security;

drop policy if exists friend_messages_read on public.friend_messages;
create policy friend_messages_read on public.friend_messages for select to authenticated
  using (lower(from_email) = public.avora_email() or lower(to_email) = public.avora_email());

drop policy if exists friend_messages_send on public.friend_messages;
create policy friend_messages_send on public.friend_messages for insert to authenticated
  with check (lower(from_email) = public.avora_email() and public.avora_is_friend(to_email));

-- Marca como leídos los mensajes que me mandó `p_email`.
create or replace function public.avora_mark_chat_read(p_email text)
  returns void language plpgsql security definer set search_path = public as $$
declare me text := public.avora_email();
begin
  if me = '' then raise exception 'Necesitás iniciar sesión.'; end if;
  update public.friend_messages set read_at = now()
    where lower(to_email) = me and lower(from_email) = lower(p_email) and read_at is null;
end $$;

grant select, insert on public.friend_messages to authenticated;
grant execute on function public.avora_mark_chat_read(text) to authenticated;
